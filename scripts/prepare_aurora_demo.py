"""Opt-in service-based Aurora import; never run implicitly or delete cases.

Supports the small Aurora sample (default) and the larger expanded network
dataset (``--dataset expanded``). Both are wholly synthetic teaching data.
"""
from __future__ import annotations

import argparse
import asyncio
import getpass
import hashlib
import json
import sys
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_DATASET = "aurora"

DATASETS = {
    "aurora": {
        "case_id": "SYNTHETIC-AURORA-DEMO-2026",
        "title": "SYNTHETIC FICTION - Aurora staged transfer (not real evidence)",
        "image": "tests/demo_case/aurora_fiction/aurora_fiction.img",
        "hash": "1c9952928f4c7c322b6e21732a7d5ed742cf90e83c347f0f8c995e586faf3310",
        "label": "Aurora",
    },
    "expanded": {
        "case_id": "SYNTHETIC-AURORA-EXPANDED-2026",
        "title": "SYNTHETIC FICTION - Aurora expanded network (not real evidence)",
        "image": "tests/demo_case/aurora_expanded/aurora_expanded.img",
        "hash": "3334c87a283ecb44c97bb2405a02a80e36745a79ba3b87506ef36f934d3076bd",
        "label": "Aurora expanded",
    },
}


def validate_worker(url: str) -> None:
    parsed = urlsplit(url)
    if (parsed.scheme != "http" or parsed.hostname not in {"127.0.0.1", "::1"}
            or parsed.username or parsed.password or parsed.query or parsed.fragment
            or parsed.path not in {"", "/"}):
        raise ValueError("Worker must be literal loopback HTTP with no credentials/path")


async def prepare(username: str, dataset: str = DEFAULT_DATASET) -> None:
    # Imports are delayed: --help/default usage never opens config or database.
    sys.path.insert(0, str(ROOT))
    import httpx

    from app.analysis.service import AnalysisService
    from app.auth.service import AuthService
    from app.cases.service import CaseService
    from app.config import get_config
    from app.db import load_all_models
    from app.db.session import get_session_factory
    from app.evidence.models import HashAlgorithm
    from app.evidence.service import EvidenceService
    from app.examination.models import ExaminationOperation, JobStatus
    from app.examination.profiles import profile_parameters
    from app.examination.service import ExaminationService

    image = ROOT / DATASETS[dataset]["image"]
    image_hash = DATASETS[dataset]["hash"]
    case_id = DATASETS[dataset]["case_id"]
    if hashlib.sha256(image.read_bytes()).hexdigest() != image_hash:
        raise ValueError(f"Bundled image differs from the exact synthetic {dataset} dataset")
    config = get_config()
    validate_worker(config.worker.url)
    if not config.analysis.enabled:
        raise ValueError("Analysis must be enabled; no configuration will be changed")

    # Defense in depth: even an accidental LLM branch in this process fails closed.
    async def reject_model(*args, **kwargs):
        raise RuntimeError("Model calls forbidden by Aurora preparation script")

    AnalysisService._extract_with_llm = reject_model
    load_all_models()
    password = getpass.getpass(f"Password for existing IDFA user {username}: ")
    with get_session_factory()() as session:
        user = AuthService(session).authenticate_user(username, password)
        if user is None or not user.is_active:
            raise PermissionError("Existing active user authentication required")
        cases = CaseService(session)
        if cases.get_case_by_case_id(case_id) is not None:
            raise ValueError(f"{case_id} already exists; refusing to alter or replace it")

        # No /health request: it probes model servers. /openapi.json is local only.
        async with httpx.AsyncClient(trust_env=False, follow_redirects=False) as client:
            response = await client.get(config.worker.url.rstrip("/") + "/openapi.json", timeout=10)
            response.raise_for_status()
            if "/examine" not in response.json().get("paths", {}):
                raise ValueError("Expected local examination worker not found")

        case = cases.create_case(
            case_id, DATASETS[dataset]["title"],
            "Wholly fictional training data; reserved addresses; no real evidence.",
            "Distinguish preparation from delivery; include block and cancellation.",
            "low", user,
        )
        evidence = EvidenceService(session).register_evidence(
            case.id, f"SYNTHETIC {DATASETS[dataset]['label']} FAT12 teaching image", str(image),
            description="Fictional generated bytes, not an acquisition.",
            registered_by=user, copy_to_store=False,
            reference_hashes={HashAlgorithm.SHA256: image_hash},
        )
        examination = ExaminationService(session)
        try:
            exam = examination.create_job(
                case.id, evidence.id, ExaminationOperation.FILE_TRAVERSAL,
                parameters=profile_parameters("fast"), created_by=user,
            )
            analysis = AnalysisService(session)
            # Persist explicit safe parameters BEFORE worker dispatch. The completion
            # enqueue returns this existing job rather than creating an unsafe one.
            job = analysis.enqueue_for_examination(
                case.id, evidence.id, exam.id, user, manual=True,
                parameters={"llm_enabled": False, "profile": "fast",
                            "build_timeline": True, "build_relationships": True,
                            "max_entities_per_artifact": 80},
            )
            if job is None or json.loads(job.parameters_json)["llm_enabled"] is not False:
                raise RuntimeError("Could not establish no-model analysis before dispatch")
            if json.loads(exam.parameters_json)["profile"] != "fast":
                raise RuntimeError("Fast examination profile was not preserved")
            session.commit()
            print(f"Created {case_id}; database ID={case.id}. No existing case changed.")
            # Disable environment proxies/redirects for every worker request too.
            examination._client = httpx.AsyncClient(trust_env=False, follow_redirects=False)
            if not await examination.start_job(exam.id) or exam.status != JobStatus.COMPLETED:
                raise RuntimeError(f"Examination incomplete: {exam.error_message}; case retained")
            session.refresh(job)
            if json.loads(job.parameters_json)["llm_enabled"] is not False:
                raise RuntimeError("Unsafe analysis parameters; refusing dispatch")
            result = await analysis.run(job.id, user)
            print(json.dumps(result, indent=2))
            if not result.get("ok"):
                raise RuntimeError("Analysis incomplete; case retained, nothing deleted")
            print(f"Prepared. Open the labelled {DATASETS[dataset]['label']} case; "
                  "use keyword search (no embeddings).")
        finally:
            await examination.close()


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--create", action="store_true",
                        help="permit creation in configured database")
    parser.add_argument("--confirm-gui-not-in-aurora", action="store_true",
                        help="attest GUI is closed or remains in another case until completion")
    parser.add_argument("--username", default="admin")
    parser.add_argument("--dataset", choices=sorted(DATASETS), default=DEFAULT_DATASET,
                        help="bundled synthetic image to import (default: aurora)")
    args = parser.parse_args(argv)
    if not args.create:
        parser.print_help()
        return 0
    if not args.confirm_gui_not_in_aurora:
        parser.error("Close GUI or keep another case open; pass --confirm-gui-not-in-aurora")
    asyncio.run(prepare(args.username, args.dataset))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
